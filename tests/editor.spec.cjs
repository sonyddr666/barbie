const { test, expect } = require('@playwright/test');

async function openEditor(page) {
  const errors = [];
  page.on('pageerror', e => { errors.push(e.message); console.log('Editor error:', e.message); });
  page.on('console', m => { if (m.type() === 'error') console.log('Editor console:', m.text()); });
  await page.goto('/editor.html?test');
  await page.waitForFunction(() => window.__ENGINE_TEST__, null, { timeout: 15000 });
  return errors;
}

test('editor: construção por clique, inspector, desfazer, recorte e JSON persistente', async ({ page }, testInfo) => {
  const errors = await openEditor(page);
  await page.screenshot({ path: testInfo.outputPath('editor-start.png') });
  await page.locator('#newProject').click();
  await page.getByRole('button', { name: 'Substituir projeto' }).click();
  await page.locator('#viewTop').click();
  await page.locator('.palette-item[data-type="floor"]').click();
  const viewport = await page.locator('#viewport').boundingBox();
  await page.mouse.click(viewport.x + viewport.width * .55, viewport.y + viewport.height * .5);
  let data = await page.evaluate(() => window.__ENGINE_TEST__.project());
  expect(data.entities).toHaveLength(1);
  expect(data.entities[0].type).toBe('floor');
  await page.locator('#selectTool').click();
  await page.locator('#objectName').fill('Piso do meu setor'); await page.locator('#objectName').press('Tab');
  await page.locator('#sizeFields input[data-axis="0"]').fill('16'); await page.locator('#sizeFields input[data-axis="0"]').press('Tab');
  await page.locator('#sizeFields input[data-axis="2"]').fill('16'); await page.locator('#sizeFields input[data-axis="2"]').press('Tab');
  await page.locator('#duplicateButton').click();
  expect((await page.evaluate(() => window.__ENGINE_TEST__.project())).entities).toHaveLength(2);
  await page.locator('#undoButton').click();
  expect((await page.evaluate(() => window.__ENGINE_TEST__.project())).entities).toHaveLength(1);
  await page.locator('#redoButton').click();
  expect((await page.evaluate(() => window.__ENGINE_TEST__.project())).entities).toHaveLength(2);
  await page.locator('#deleteButton').click();
  const id = await page.evaluate(() => window.__ENGINE_TEST__.place('spawn', [0, 0, 2]));
  await page.locator('#materialSlot').selectOption('cloth');
  await page.locator('#textureEdit').click();
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = c.height = 32; const x = c.getContext('2d'); x.fillStyle = '#ff3399'; x.fillRect(0, 0, 32, 32); x.fillStyle = '#aadd77'; x.fillRect(0, 0, 16, 16); return c.toDataURL('image/png').split(',')[1]; });
  await page.locator('#textureFile').setInputFiles({ name: 'roupa-personalizada.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.waitForTimeout(250);
  await page.locator('#cropResolution').selectOption('128');
  await page.locator('#applyCrop').click();
  await expect(page.locator('#textureModal')).toBeHidden();
  data = await page.evaluate(() => window.__ENGINE_TEST__.project());
  expect(data.entities.find(e => e.id === id).character.appearance.cloth.preset).toBe('custom');
  expect(Object.values(data.assets)[0].name).toBe('roupa-personalizada.png');
  await page.locator('#headScale').fill('1.3'); await page.locator('#headScale').press('Tab');
  await page.locator('#saveProject').click();
  await expect(page.locator('#saveState')).toContainText('Salvo no navegador');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#exportProject').click();
  const download = await downloadPromise;
  const stream = await download.createReadStream(); const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const exported = Buffer.concat(chunks), json = JSON.parse(exported.toString());
  expect(json.format).toBe('palace-engine'); expect(Object.keys(json.assets)).toHaveLength(1);
  await page.reload(); await page.waitForFunction(() => window.__ENGINE_TEST__);
  expect((await page.evaluate(() => window.__ENGINE_TEST__.project())).entities.find(e => e.id === id).character.headScale).toBe(1.3);
  await page.locator('#projectFile').setInputFiles({ name: 'setor.palace.json', mimeType: 'application/json', buffer: exported });
  await page.getByRole('button', { name: 'Substituir projeto' }).click();
  data = await page.evaluate(() => window.__ENGINE_TEST__.project());
  expect(data.entities.find(e => e.id === id).character.appearance.cloth.preset).toBe('custom');
  expect(data.assets[json.entities.find(e => e.id === id).character.appearance.cloth.texture].data).toMatch(/^data:image\/png/);
  await page.locator('#playButton').click();
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).appearance.cloth.preset).toBe('custom');
  await page.keyboard.press('Escape');
  await page.evaluate(id => window.__ENGINE_TEST__.select(id), id);
  await page.locator('#focusButton').click();
  await page.locator('#viewPerspective').click();
  await page.screenshot({ path: testInfo.outputPath('editor-character.png') });
  expect(errors).toEqual([]);
});

test('engine: mapa executável, colisão girada, checkpoint, objetivo e retorno à edição', async ({ page }, testInfo) => {
  const errors = await openEditor(page);
  await page.locator('#loadExample').click(); await page.getByRole('button', { name: 'Substituir projeto' }).click();
  const project = await page.evaluate(() => window.__ENGINE_TEST__.project());
  const spawn = project.entities.find(e => e.type === 'spawn'), disks = project.entities.filter(e => e.type === 'disk'), npc = project.entities.find(e => e.type === 'character' && e.character.role === 'npc'), capsule = project.entities.find(e => e.type === 'capsule'), exit = project.entities.find(e => e.type === 'exit');
  await page.locator('#playButton').click();
  await expect(page.locator('body')).toHaveClass('playing');
  await page.screenshot({ path: testInfo.outputPath('engine-play.png') });
  await page.evaluate(() => { const t = window.__ENGINE_TEST__; t.teleport(0, 0, -8); t.noise(); for (let i = 0; i < 100; i++) t.step(.04); });
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).health).toBeLessThan(6);
  await page.evaluate(() => { const t = window.__ENGINE_TEST__; t.teleport(0, 0, 11); window.dispatchEvent(new KeyboardEvent('keydown', { code: 'KeyS' })); for (let i = 0; i < 40; i++) t.step(.04); window.dispatchEvent(new KeyboardEvent('keyup', { code: 'KeyS' })); });
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).position[2]).toBeLessThan(11.7);
  await page.evaluate(pos => window.__ENGINE_TEST__.teleport(...pos), npc.position);
  await page.keyboard.press('e');
  await expect(page.locator('#infoTitle')).toHaveText(npc.name);
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await page.evaluate(pos => window.__ENGINE_TEST__.teleport(...pos), disks[0].position); await page.keyboard.press('e');
  await expect(page.locator('#runtimeDisks')).toHaveText('1 / 3');
  await page.evaluate(pos => window.__ENGINE_TEST__.teleport(...pos), capsule.position); await page.keyboard.press('e');
  await page.evaluate(pos => window.__ENGINE_TEST__.teleport(...pos), disks[1].position); await page.keyboard.press('e');
  await expect(page.locator('#runtimeDisks')).toHaveText('2 / 3');
  for (let i = 0; i < 6; i++) await page.evaluate(() => window.__ENGINE_TEST__.damage());
  await expect(page.locator('#runtimeDisks')).toHaveText('1 / 3');
  for (const d of disks.slice(1)) { await page.evaluate(pos => window.__ENGINE_TEST__.teleport(...pos), d.position); await page.keyboard.press('e'); }
  await expect(page.locator('#runtimeDisks')).toHaveText('3 / 3');
  await page.evaluate(pos => window.__ENGINE_TEST__.teleport(pos[0], pos[1], pos[2] + 1.3), exit.position); await page.keyboard.press('e');
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).won).toBe(true);
  await page.keyboard.press('Escape'); await expect(page.locator('body')).not.toHaveClass('playing');
  expect(await page.evaluate(() => window.__ENGINE_TEST__.project())).toEqual(project);
  await page.locator('#playButton').click();
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).disks).toEqual([]);
  await page.keyboard.press('Escape');
  expect(errors).toEqual([]);
});

test('engine: parede girada, rampa girada e importação inválida preservam a cena', async ({ page }) => {
  const errors = await openEditor(page);
  await page.locator('#newProject').click(); await page.getByRole('button', { name: 'Substituir projeto' }).click();
  await page.evaluate(() => {
    const t = window.__ENGINE_TEST__, floor = t.place('floor', [0, 0, 0]), spawn = t.place('spawn', [0, 0, 5]);
    const p = t.project(); p.entities.find(e => e.id === floor).size = [20, .3, 20];
    const w = p.entities.find(e => e.id === spawn); w.character.speed = 3.4;
    t.load(p); t.place('wall', [0, 0, 0]);
  });
  await page.locator('#objectRotation').fill('45'); await page.locator('#objectRotation').press('Tab');
  const wall = (await page.evaluate(() => window.__ENGINE_TEST__.project())).entities.find(e => e.type === 'wall');
  expect(wall.rotation).toBeCloseTo(Math.PI / 4);
  await page.evaluate(() => window.__ENGINE_TEST__.place('ramp', [4, 0, 0]));
  await page.locator('#objectRotation').fill('90'); await page.locator('#objectRotation').press('Tab');
  await page.locator('#playButton').click();
  await page.evaluate(() => { const t = window.__ENGINE_TEST__; t.teleport(0, 0, 2); window.dispatchEvent(new KeyboardEvent('keydown', { code: 'KeyW' })); for (let i = 0; i < 40; i++) t.step(.04); window.dispatchEvent(new KeyboardEvent('keyup', { code: 'KeyW' })); });
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).position[2]).toBeGreaterThan(.4);
  await page.evaluate(() => { const t = window.__ENGINE_TEST__; t.teleport(6, 0, 0); window.dispatchEvent(new KeyboardEvent('keydown', { code: 'KeyA' })); for (let i = 0; i < 31; i++) t.step(.04); window.dispatchEvent(new KeyboardEvent('keyup', { code: 'KeyA' })); });
  expect((await page.evaluate(() => window.__ENGINE_TEST__.runtime())).position[1]).toBeGreaterThan(1.8);
  await page.keyboard.press('Escape');
  const before = await page.evaluate(() => window.__ENGINE_TEST__.project());
  await page.locator('#projectFile').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong","entities":[]}') });
  await expect(page.locator('#editorToast')).toContainText('Formato inválido');
  expect(await page.evaluate(() => window.__ENGINE_TEST__.project())).toEqual(before);
  expect(errors).toEqual([]);
});
